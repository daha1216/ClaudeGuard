    fn find_owned_windows(window_title: &str) -> Vec<HWND> {
        use windows::Win32::UI::WindowsAndMessaging::{FindWindowExW, GetWindowThreadProcessId};

        let mut utf16: Vec<u16> = window_title.encode_utf16().collect();
        utf16.push(0);
        let self_pid = std::process::id();
        let mut prev = HWND::default();
        let mut found = Vec::new();

        loop {
            let Ok(hwnd) = (unsafe {
                FindWindowExW(
                    HWND::default(),
                    prev,
                    PCWSTR::null(),
                    PCWSTR(utf16.as_ptr()),
                )
            }) else {
                break;
            };
            if hwnd.0.is_null() {
                break;
            }
            let mut pid = 0u32;
            unsafe {
                GetWindowThreadProcessId(hwnd, Some(&mut pid));
            }
            if pid == self_pid {
                found.push(hwnd);
            }
            prev = hwnd;
        }
        found
    }

    /// Ensures a top-level minimizable GPUI window carries `WS_CAPTION` (still rendered frameless
    /// via GPUI's `WM_NCCALCSIZE` `rgrc[0].top = saved_top` override) and explicitly enables DWM
    /// hardware-accelerated transitions so Windows 11 plays the native high-refresh fluid scale
    /// minimize-to-taskbar, restore-from-taskbar, and maximize/unmaximize animations.
    fn ensure_win11_smooth_dwm_frame(hwnd: HWND) {
        use windows::Win32::Foundation::BOOL;
        use windows::Win32::Graphics::Dwm::{
            DWMWA_TRANSITIONS_FORCEDISABLED, DwmSetWindowAttribute,
        };
        use windows::Win32::UI::WindowsAndMessaging::{
            SWP_FRAMECHANGED, SWP_NOACTIVATE, SWP_NOCOPYBITS, SWP_NOMOVE, SWP_NOOWNERZORDER,
            SWP_NOREPOSITION, SWP_NOSENDCHANGING, SWP_NOSIZE, SWP_NOZORDER, SetWindowPos,
            WS_CAPTION, WS_MINIMIZEBOX,
        };

        let cur_style = unsafe { get_window_style(hwnd) };
        // Never alter borderless PopUp windows (e.g. Quick HUD) that have no minimize box.
        if (cur_style & WS_MINIMIZEBOX.0) == 0 {
            return;
        }
        if (cur_style & WS_CAPTION.0) != WS_CAPTION.0 {
            unsafe {
                set_window_style(hwnd, cur_style | WS_CAPTION.0);
                let _ = SetWindowPos(
                    hwnd,
                    HWND::default(),
                    0,
                    0,
                    0,
                    0,
                    SWP_FRAMECHANGED
                        | SWP_NOACTIVATE
                        | SWP_NOCOPYBITS
                        | SWP_NOMOVE
                        | SWP_NOOWNERZORDER
                        | SWP_NOREPOSITION
                        | SWP_NOSENDCHANGING
                        | SWP_NOSIZE
                        | SWP_NOZORDER,
                );
            }
        }
        let disable_transitions = BOOL(0);
        unsafe {
            let _ = DwmSetWindowAttribute(
                hwnd,
                DWMWA_TRANSITIONS_FORCEDISABLED,
                &disable_transitions as *const _ as *const _,
                std::mem::size_of_val(&disable_transitions) as u32,
            );
        }
    }

    /// Applies Windows 11 native DWM rounded corners (`DWMWCP_ROUND`), subtle border color,
    /// immersive dark-mode chrome alignment, smooth DWM transition frame bits (`WS_CAPTION` +
    /// `DWMWA_TRANSITIONS_FORCEDISABLED = 0`), and embedded window icons (`WM_SETICON`) to every
    /// matching GPUI window owned by this process. Safely no-ops DWM calls on Windows 10.
    pub fn apply_win11_round_corners(window_title: &str, border_rgb: u32) {
        use windows::Win32::Foundation::BOOL;
        use windows::Win32::Graphics::Dwm::{
            DWMWA_BORDER_COLOR, DWMWA_USE_IMMERSIVE_DARK_MODE, DWMWA_WINDOW_CORNER_PREFERENCE,
            DWMWCP_ROUND, DwmSetWindowAttribute,
        };

        let r = (border_rgb >> 16) & 0xFF;
        let g = (border_rgb >> 8) & 0xFF;
        let b = border_rgb & 0xFF;
        let colorref: u32 = r | (g << 8) | (b << 16);
        let dark_mode = BOOL::from((r + g + b) < 384);
        let corner_pref = DWMWCP_ROUND;

        for hwnd in find_owned_windows(window_title) {
            ensure_win11_smooth_dwm_frame(hwnd);
            unsafe {
                let _ = DwmSetWindowAttribute(
                    hwnd,
                    DWMWA_USE_IMMERSIVE_DARK_MODE,
                    &dark_mode as *const _ as *const _,
                    std::mem::size_of_val(&dark_mode) as u32,
                );
                let _ = DwmSetWindowAttribute(
                    hwnd,
                    DWMWA_WINDOW_CORNER_PREFERENCE,
                    &corner_pref as *const _ as *const _,
                    std::mem::size_of_val(&corner_pref) as u32,
                );
                let _ = DwmSetWindowAttribute(
                    hwnd,
                    DWMWA_BORDER_COLOR,
                    &colorref as *const _ as *const _,
                    std::mem::size_of_val(&colorref) as u32,
                );
            }
            apply_window_icon(hwnd);
        }
    }

    /// Minimizes a GPUI window via native `WM_SYSCOMMAND(SC_MINIMIZE)` so Windows 11 DWM plays
    /// its hardware-accelerated fluid minimize-to-taskbar transition instead of abrupt `SW_MINIMIZE`.
    pub fn minimize_window_smooth(window_title: &str) -> bool {
        use windows::Win32::UI::WindowsAndMessaging::{SC_MINIMIZE, WM_SYSCOMMAND};

        let Some(hwnd) = find_owned_windows(window_title).into_iter().next() else {
            return false;
        };
        ensure_win11_smooth_dwm_frame(hwnd);
        unsafe {
            PostMessageW(hwnd, WM_SYSCOMMAND, WPARAM(SC_MINIMIZE as usize), LPARAM(0)).is_ok()
        }
    }

    /// Toggles maximize/restore on a GPUI window via native `WM_SYSCOMMAND(SC_MAXIMIZE / SC_RESTORE)`
    /// so both directions use Windows 11 DWM fluid zoom transitions and properly un-maximize.
    pub fn toggle_maximize_window_smooth(window_title: &str) -> bool {
        use windows::Win32::UI::WindowsAndMessaging::{
            IsZoomed, SC_MAXIMIZE, SC_RESTORE, WM_SYSCOMMAND,
        };

        let Some(hwnd) = find_owned_windows(window_title).into_iter().next() else {
            return false;
        };
        ensure_win11_smooth_dwm_frame(hwnd);
        let cmd = if unsafe { IsZoomed(hwnd).as_bool() } {
            SC_RESTORE
        } else {
            SC_MAXIMIZE
        };
        unsafe { PostMessageW(hwnd, WM_SYSCOMMAND, WPARAM(cmd as usize), LPARAM(0)).is_ok() }
    }

    /// Restores a minimized GPUI window owned by the current process via native
    /// `WM_SYSCOMMAND(SC_RESTORE)` so Windows 11 DWM plays its smooth expand-from-taskbar
    /// animation. Returns `true` if the window was minimized and restore was initiated.
    pub fn restore_window_if_minimized(title: &str) -> bool {
        use windows::Win32::UI::WindowsAndMessaging::{IsIconic, SC_RESTORE, WM_SYSCOMMAND};

        for hwnd in find_owned_windows(title) {
            unsafe {
                if IsIconic(hwnd).as_bool() {
                    ensure_win11_smooth_dwm_frame(hwnd);
                    let _ =
                        PostMessageW(hwnd, WM_SYSCOMMAND, WPARAM(SC_RESTORE as usize), LPARAM(0));
                    let _ = SetForegroundWindow(hwnd);
                    return true;
                }
            }
        }
        false
    }

    /// Queries the Windows accessibility setting "Animation effects" (`SPI_GETCLIENTAREAANIMATION`).
    /// Returns `true` when client-area animations are disabled (`enabled == 0`), defaulting to `false` on error.
    pub fn query_windows_reduce_motion() -> bool {
        let mut enabled: i32 = 1;
        let ok = unsafe {
            SystemParametersInfoW(
                SPI_GETCLIENTAREAANIMATION,
                0,
                Some(&mut enabled as *mut i32 as *mut c_void),
                SYSTEM_PARAMETERS_INFO_UPDATE_FLAGS(0),
            )
        }
        .is_ok();
        ok && enabled == 0
    }
    /// Signals an already-running ClaudeGuard v4 tray window if present.
    /// - In normal mode (`!is_demo`), wakes the existing instance (`ToggleHud` or `OpenConsole`)
    ///   and returns `true` so the caller can exit cleanly without spawning duplicate tray icons.
    /// - In `--demo` mode, asks any lingering tray instance to quit (`CMD_QUIT_GUI`) so demo runs
    ///   never accumulate stale background processes, then returns `false` to continue startup.
    pub fn signal_existing_tray_instance(
        is_demo: bool,
        start_hud: bool,
        start_in_tray: bool,
    ) -> bool {
        use windows::Win32::UI::WindowsAndMessaging::FindWindowW;

        let Ok(hwnd) =
            (unsafe { FindWindowW(w!("ClaudeGuardV4TrayWindow"), w!("ClaudeGuardV4Tray")) })
        else {
            return false;
        };
        if hwnd.0.is_null() {
            return false;
        }

        if is_demo {
            let _ =
                unsafe { PostMessageW(hwnd, WM_COMMAND, WPARAM(CMD_QUIT_GUI as usize), LPARAM(0)) };
            std::thread::sleep(std::time::Duration::from_millis(80));
            return false;
        }

        if start_hud {
            let _ = unsafe {
                PostMessageW(hwnd, WM_COMMAND, WPARAM(CMD_TOGGLE_HUD as usize), LPARAM(0))
            };
        } else if !start_in_tray {
            let _ = unsafe {
                PostMessageW(
                    hwnd,
                    WM_COMMAND,
                    WPARAM(CMD_OPEN_CONSOLE as usize),
                    LPARAM(0),
                )
            };
        }
        true
    }
