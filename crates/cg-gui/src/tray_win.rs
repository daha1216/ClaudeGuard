    /// RAII Win32 named-mutex guard ensuring single-instance lifetime across normal GUI launches.
    pub struct SingleInstanceGuard {
        handle: isize,
    }

    impl Drop for SingleInstanceGuard {
        fn drop(&mut self) {
            if self.handle != 0 {
                let raw = HANDLE(self.handle as *mut c_void);
                self.handle = 0;
                // SAFETY: `raw` is exclusively owned by `SingleInstanceGuard`.
                unsafe {
                    let _ = CloseHandle(raw);
                }
            }
        }
    }

    pub enum SingleInstanceOutcome {
        Acquired(SingleInstanceGuard),
        AlreadyRunning,
    }

    /// Acquires `Local\ClaudeGuardV4GuiSingleInstance` so simultaneous launches never spawn
    /// duplicate system-tray icons before `FindWindowW` becomes visible.
    pub fn acquire_single_instance() -> SingleInstanceOutcome {
        match unsafe { CreateMutexW(None, false, w!("Local\\ClaudeGuardV4GuiSingleInstance")) } {
            Ok(handle) => {
                let already_exists = unsafe { GetLastError() } == ERROR_ALREADY_EXISTS;
                if already_exists {
                    unsafe {
                        let _ = CloseHandle(handle);
                    }
                    SingleInstanceOutcome::AlreadyRunning
                } else {
                    SingleInstanceOutcome::Acquired(SingleInstanceGuard {
                        handle: handle.0 as isize,
                    })
                }
            }
            Err(_) => SingleInstanceOutcome::Acquired(SingleInstanceGuard { handle: 0 }),
        }
    }

