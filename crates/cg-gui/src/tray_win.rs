/// Embedded 64×64 full-bleed RGBA master of the freestanding Sapphire Origami Crystal Shield
/// so the Windows notification tray matches the exact jewel-like crispness of the Desktop & Taskbar icon.
const TRAY_SHIELD_64_RGBA: &[u8] = include_bytes!("../assets/icons/brands/tray_shield_64.rgba");

/// Renders a 2x2 supersampled anti-aliased miniature ClaudeGuard Freestanding Sapphire Crystal Shield
/// directly from the embedded 64×64 artwork master, composited with a compact lower-right semantic
/// status gem (crisp pearl halo cutout for both Light & Dark Windows 11 taskbars).
/// Returns little-endian `0xAARRGGBB` pixels suitable for Win32 32bpp `CreateBitmap`.
fn render_tray_shield_argb(size: usize, status_rgb: (u8, u8, u8)) -> Vec<u32> {
    const SRC_DIM: usize = 64;
    const SS: usize = 2;
    let s = size.max(16);
    let mut pixels = vec![0u32; s * s];
    let inv_total = 1.0 / (SS * SS) as f32;
    let (sr, sg, sb) = (
        status_rgb.0 as f32 / 255.0,
        status_rgb.1 as f32 / 255.0,
        status_rgb.2 as f32 / 255.0,
    );

    let sample_rgba = |ix: usize, iy: usize| -> (f32, f32, f32, f32) {
        let off = (iy * SRC_DIM + ix) * 4;
        if off + 3 < TRAY_SHIELD_64_RGBA.len() {
            (
                TRAY_SHIELD_64_RGBA[off] as f32 / 255.0,
                TRAY_SHIELD_64_RGBA[off + 1] as f32 / 255.0,
                TRAY_SHIELD_64_RGBA[off + 2] as f32 / 255.0,
                TRAY_SHIELD_64_RGBA[off + 3] as f32 / 255.0,
            )
        } else {
            (0.0, 0.0, 0.0, 0.0)
        }
    };

    let sample_bilinear = |u: f32, v: f32| -> (f32, f32, f32, f32) {
        let fx = (u * (SRC_DIM - 1) as f32).clamp(0.0, (SRC_DIM - 1) as f32);
        let fy = (v * (SRC_DIM - 1) as f32).clamp(0.0, (SRC_DIM - 1) as f32);
        let x0 = fx.floor() as usize;
        let y0 = fy.floor() as usize;
        let x1 = (x0 + 1).min(SRC_DIM - 1);
        let y1 = (y0 + 1).min(SRC_DIM - 1);
        let tx = fx - x0 as f32;
        let ty = fy - y0 as f32;

        let p00 = sample_rgba(x0, y0);
        let p10 = sample_rgba(x1, y0);
        let p01 = sample_rgba(x0, y1);
        let p11 = sample_rgba(x1, y1);

        let lerp4 = |a: (f32, f32, f32, f32), b: (f32, f32, f32, f32), t: f32| {
            (
                a.0 + (b.0 - a.0) * t,
                a.1 + (b.1 - a.1) * t,
                a.2 + (b.2 - a.2) * t,
                a.3 + (b.3 - a.3) * t,
            )
        };
        lerp4(lerp4(p00, p10, tx), lerp4(p01, p11, tx), ty)
    };

    for y in 0..s {
        for x in 0..s {
            let mut acc_r = 0.0_f32;
            let mut acc_g = 0.0_f32;
            let mut acc_b = 0.0_f32;
            let mut acc_a = 0.0_f32;

            for sy in 0..SS {
                for sx in 0..SS {
                    let u = (x as f32 + (sx as f32 + 0.5) / SS as f32) / s as f32;
                    let v = (y as f32 + (sy as f32 + 0.5) / SS as f32) / s as f32;

                    // Slight 2% up-left nudge keeps the full-bleed crystal shield centered while giving
                    // the lower-right status gem crisp breathing room.
                    let (mut cr, mut cg, mut cb, mut ca) =
                        sample_bilinear((u + 0.02).clamp(0.0, 1.0), (v + 0.01).clamp(0.0, 1.0));

                    let gd = ((u - 0.78).powi(2) + (v - 0.78).powi(2)).sqrt();
                    if gd <= 0.185 {
                        let hl = (1.0 - ((u - 0.74).powi(2) + (v - 0.73).powi(2)).sqrt() * 4.5)
                            .clamp(0.0, 1.0)
                            * 0.28;
                        cr = (sr + hl * (1.0 - sr)).clamp(0.0, 1.0);
                        cg = (sg + hl * (1.0 - sg)).clamp(0.0, 1.0);
                        cb = (sb + hl * (1.0 - sb)).clamp(0.0, 1.0);
                        ca = 1.0;
                    } else if gd <= 0.245 {
                        cr = 0.98;
                        cg = 0.99;
                        cb = 1.0;
                        ca = 0.96;
                    }

                    acc_r += cr * ca;
                    acc_g += cg * ca;
                    acc_b += cb * ca;
                    acc_a += ca;
                }
            }

            let alpha = (acc_a * inv_total).clamp(0.0, 1.0);
            let (pr, pg, pb) = if acc_a > 1e-5 {
                (
                    (acc_r / acc_a).clamp(0.0, 1.0),
                    (acc_g / acc_a).clamp(0.0, 1.0),
                    (acc_b / acc_a).clamp(0.0, 1.0),
                )
            } else {
                (0.0, 0.0, 0.0)
            };
            let a_u8 = (alpha * 255.0).round() as u32;
            let r_u8 = (pr * 255.0).round() as u32;
            let g_u8 = (pg * 255.0).round() as u32;
            let b_u8 = (pb * 255.0).round() as u32;
            pixels[y * s + x] = (a_u8 << 24) | (r_u8 << 16) | (g_u8 << 8) | b_u8;
        }
    }

    pixels
}

