#[cfg(any(windows, test))]
const MAX_PENDING_BALLOONS: usize = 16;

/// Pushes a balloon notification into a bounded FIFO queue, dropping the oldest item if full.
#[cfg(any(windows, test))]
fn enqueue_balloon(queue: &mut VecDeque<(String, String, bool)>, item: (String, String, bool)) {
    while queue.len() >= MAX_PENDING_BALLOONS {
        queue.pop_front();
    }
    queue.push_back(item);
}

/// Copies `src` as NUL-terminated UTF-16 into `dst`, never splitting UTF-16 surrogate pairs
/// and always leaving at least one trailing `0` code unit when `!dst.is_empty()`.
#[cfg(any(windows, test))]
pub(crate) fn copy_utf16_truncated(src: &str, dst: &mut [u16]) -> usize {
    if dst.is_empty() {
        return 0;
    }
    dst.fill(0);
    let max_units = dst.len() - 1;
    let mut written = 0usize;
    for ch in src.chars() {
        let mut buf = [0u16; 2];
        let encoded = ch.encode_utf16(&mut buf);
        if written + encoded.len() > max_units {
            break;
        }
        dst[written..written + encoded.len()].copy_from_slice(encoded);
        written += encoded.len();
    }
    dst[written] = 0;
    written
}

/// Ensures `szInfo` is never empty when posting `NIF_INFO` (`Shell_NotifyIconW` treats an empty
/// `szInfo` string as a command to cancel/dismiss existing notifications rather than showing one).
#[cfg(any(windows, test))]
pub(crate) fn non_empty_balloon_texts<'a>(title: &'a str, body: &'a str) -> (&'a str, &'a str) {
    let safe_title = if title.trim().is_empty() {
        "ClaudeGuard"
    } else {
        title.trim()
    };
    let safe_body = if body.trim().is_empty() {
        safe_title
    } else {
        body.trim()
    };
    (safe_title, safe_body)
}

/// Suppresses the trailing `WM_LBUTTONUP` generated by the second click of a tray double-click
/// so opening the main console never accidentally toggles the quick HUD back open.
#[cfg(any(windows, test))]
#[derive(Default)]
struct DoubleClickGuard {
    suppress_next_up: bool,
    last_dblclk_at: Option<Instant>,
}

#[cfg(any(windows, test))]
impl DoubleClickGuard {
    const SUPPRESS_WINDOW: Duration = Duration::from_millis(500);

    fn record_double_click(&mut self, now: Instant) {
        self.suppress_next_up = true;
        self.last_dblclk_at = Some(now);
    }

    fn should_emit_single_click(&mut self, now: Instant) -> bool {
        if !self.suppress_next_up {
            return true;
        }
        self.suppress_next_up = false;
        let within_window = self
            .last_dblclk_at
            .is_some_and(|at| now.saturating_duration_since(at) < Self::SUPPRESS_WINDOW);
        !within_window
    }
}

